function gradeTicket(ticket, board, at = Date.now()) {
	if (!board) return blank(ticket, "unchecked", "Scoreboard has not returned. The archive result is not a settlement.");
	if (ticket.kind === "prop" || ticket.kind === "parlay") return blank(ticket, "uncovered", ticket.kind === "prop" ? "Player stat is not on the team scoreboard. The archive win is not a grade." : "Parlay legs are not stored. The archive win is not a grade.", { result: "pending" });
	const game = findGame(board, ticket.matchup, ticket.week);
	if (!game) return blank(ticket, "uncovered", "No scoreboard game for this matchup. Not graded.", { result: "pending" });
	if (game.status === "postponed" || game.status === "canceled" || game.status === "suspended") return blank(ticket, "void", `${game.status}. Original retained. Not a loss.`, {
		result: "pending",
		score: scoreLine(game),
		settlementSource: sourceOf(game),
		settlementTimestamp: at
	});
	if (game.status !== "final") return blank(ticket, "pending", `${game.detail || game.statusName}. Not final. Settlement source stays empty.`, { result: "pending" });
	const graded = gradeMarket(ticket, game);
	if (!graded) return blank(ticket, "uncovered", "Side could not be read against the final. Not graded.", { result: "pending" });
	const agrees = ticket.result === "pending" ? null : ticket.result === graded.result;
	const disagree = agrees === false ? ` Archive recorded ${ticket.result}.` : "";
	return blank(ticket, graded.result, `${graded.note}${disagree}`, {
		result: graded.result,
		score: scoreLine(game),
		settlementSource: sourceOf(game),
		settlementTimestamp: at,
		agrees
	});
}
