function impliedProb(american) {
	if (american < 0) return -american / (-american + 100);
	return 100 / (american + 100);
}
function americanToDecimal(american) {
	if (american < 0) return 1 + 100 / -american;
	return 1 + american / 100;
}
function probToAmerican(p) {
	const clamped = Math.min(.97, Math.max(.03, p));
	if (clamped >= .5) return Math.round(-100 * clamped / (1 - clamped));
	return Math.round(100 * (1 - clamped) / clamped);
}
/** Profit per 1 unit risked at given American price. */
function evFromProb(p, american) {
	return p * (americanToDecimal(american) - 1) - (1 - p);
}
/** Fractional Kelly, capped. */
function kellyFraction(p, american, fraction = .5, cap = .5) {
	const b = americanToDecimal(american) - 1;
	if (b <= 0) return 0;
	const f = (b * p - (1 - p)) / b;
	return Math.min(cap, Math.max(0, f * fraction));
}
